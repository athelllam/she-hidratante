-- Registro idempotente dos e-mails de conquista da equipe avançada.
-- Executar uma vez no SQL Editor do Supabase antes do deploy.
create table if not exists public.affiliate_team_level_notifications (
  id bigint generated by default as identity primary key,
  affiliate_id bigint not null references public.affiliates(id) on delete cascade,
  month_key text not null check (month_key ~ '^\d{4}-\d{2}$'),
  level_key text not null check (level_key in ('advanced_1', 'advanced_2')),
  status text not null default 'sending' check (status in ('sending', 'sent')),
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  unique (affiliate_id, month_key, level_key)
);

create index if not exists affiliate_team_level_notifications_month_idx
  on public.affiliate_team_level_notifications(month_key, level_key);
