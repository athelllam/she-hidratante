-- Inscrições Web Push por dispositivo. Execute uma única vez no Supabase SQL Editor.
create table if not exists public.affiliate_push_subscriptions (
  id bigint generated by default as identity primary key,
  affiliate_id bigint not null references public.affiliates(id) on delete cascade,
  endpoint text not null unique,
  subscription jsonb not null,
  user_agent text,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists affiliate_push_subscriptions_affiliate_active_idx
  on public.affiliate_push_subscriptions (affiliate_id, active);
alter table public.affiliate_push_subscriptions enable row level security;
