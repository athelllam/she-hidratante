-- Histórico dos avisos enviados pelo painel administrativo (push e e-mail).
create table if not exists public.admin_broadcast_logs (
  id bigint generated by default as identity primary key,
  channel text not null check (channel in ('push', 'email')),
  title text,
  subject text,
  message text not null,
  sent_count integer not null default 0,
  failed_count integer not null default 0,
  sent_at timestamptz not null default now()
);
create index if not exists admin_broadcast_logs_channel_sent_at_idx
  on public.admin_broadcast_logs (channel, sent_at desc);
alter table public.admin_broadcast_logs enable row level security;
