-- Compras de produtos por afiliadas: reservas de saldo e controle mensal.
alter table public.affiliate_settings
  add column if not exists affiliate_hydrant_price numeric(10,2) not null default 80,
  add column if not exists affiliate_stick_price numeric(10,2) not null default 100;

create table if not exists public.affiliate_product_purchases (
  id bigint generated by default as identity primary key,
  affiliate_id bigint not null references public.affiliates(id) on delete cascade,
  product text not null check (product in ('hydrant','stick')),
  price numeric(10,2) not null check (price > 0),
  status text not null default 'pending' check (status in ('pending','shipped','approved','rejected','cancelled')),
  full_name text not null,
  cpf text not null,
  cep text not null,
  address text not null,
  email text not null,
  phone text not null,
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  shipped_at timestamptz,
  approved_at timestamptz,
  rejected_at timestamptz
);
create index if not exists affiliate_product_purchases_affiliate_idx on public.affiliate_product_purchases(affiliate_id, created_at desc);
create index if not exists affiliate_product_purchases_status_idx on public.affiliate_product_purchases(status, created_at desc);
alter table public.affiliate_product_purchases enable row level security;
