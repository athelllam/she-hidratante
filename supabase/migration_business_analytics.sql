-- She Business Analytics: finance ledger and monthly assumptions.
-- Run in Supabase SQL Editor. Safe to re-run.
create table if not exists public.she_finance_entries (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('income','expense')),
  description text not null,
  category text not null default 'Outros',
  amount numeric(14,2) not null check (amount > 0),
  date date not null,
  competence date not null,
  status text not null default 'paid' check (status in ('paid','pending')),
  source text not null default 'manual',
  external_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists she_finance_entries_competence_idx on public.she_finance_entries (competence, kind, status);
create unique index if not exists she_finance_entries_external_source_unique on public.she_finance_entries (source, external_id) where external_id is not null;
create table if not exists public.she_finance_settings (
  id integer primary key default 1 check (id = 1),
  tax_percent numeric(7,3) not null default 0 check (tax_percent between 0 and 100),
  fee_percent numeric(7,3) not null default 0 check (fee_percent between 0 and 100),
  updated_at timestamptz not null default now()
);
insert into public.she_finance_settings (id, tax_percent, fee_percent) values (1,0,0) on conflict (id) do nothing;
-- Keep tables server-only: API uses Supabase service-role credentials after admin session validation.
alter table public.she_finance_entries enable row level security;
alter table public.she_finance_settings enable row level security;

-- Independent copy of every Yampi order for the business dashboard.
-- This table is intentionally separate from affiliate_orders so the affiliate
-- commission, notification and qualification flow remains unchanged.
create table if not exists public.she_business_orders (
  id bigint generated by default as identity primary key,
  yampi_order_id text not null unique,
  order_number text,
  status text not null default 'created',
  payment_approved boolean not null default false,
  cancelled boolean not null default false,
  total numeric(14,2) not null default 0,
  created_at timestamptz not null,
  yampi_updated_at timestamptz,
  affiliate_id bigint,
  raw_payload jsonb not null default '{}'::jsonb,
  synced_at timestamptz not null default now()
);
create index if not exists she_business_orders_created_at_idx on public.she_business_orders (created_at);
create index if not exists she_business_orders_payment_created_idx on public.she_business_orders (payment_approved, created_at);
create index if not exists she_business_orders_cancelled_created_idx on public.she_business_orders (cancelled, created_at);

-- Scroll cursor is persisted between bounded API calls, allowing the full
-- Yampi history to be imported without exceeding a Vercel function timeout.
create table if not exists public.she_business_sync_state (
  id integer primary key default 1 check (id = 1),
  scroll_id text,
  completed boolean not null default false,
  history_imported boolean not null default false,
  scanned_orders bigint not null default 0,
  synced_orders bigint not null default 0,
  cycle_started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now()
);
alter table public.she_business_sync_state add column if not exists history_imported boolean not null default false;
insert into public.she_business_sync_state (id, completed, history_imported, scanned_orders, synced_orders)
values (1, false, false, 0, 0) on conflict (id) do nothing;

alter table public.she_business_orders enable row level security;
alter table public.she_business_sync_state enable row level security;


-- General website access/session events for business analytics (separate from affiliate tracking).
create table if not exists public.she_site_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  session_id text not null,
  path text not null default '/',
  referrer text,
  event_key text not null unique,
  created_at timestamptz not null default now()
);
create index if not exists she_site_events_created_at_idx on public.she_site_events (created_at);
create index if not exists she_site_events_session_created_idx on public.she_site_events (session_id, created_at);
alter table public.she_site_events enable row level security;
